// Generates the Android string resources from src/i18n.ts so that the web and the
// Android app always share the same English and Russian texts.
//
//   node --experimental-strip-types scripts/gen-android-strings.mjs          # write files
//   node --experimental-strip-types scripts/gen-android-strings.mjs --check  # fail if outdated
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { messages } from '../src/i18n.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const resDir = resolve(root, 'android/app/src/main/res');
const TARGETS = { en: 'values/strings.xml', ru: 'values-ru/strings.xml' };
const CATEGORIES = { en: ['one', 'other'], ru: ['one', 'few', 'many', 'other'] };

const androidName = (key) => key.replace(/[.-]/g, '_');

function escapeText(text) {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"')
    .replace(/%/g, '%%')
    .replace(/^([@?])/, '\\$1');
}

/** {name} placeholders become positional %n$s arguments in order of first appearance. */
function toFormat(text, { plural }) {
  const order = [];
  const escaped = escapeText(text).replace(/\{(\w+)\}/g, (_, name) => {
    if (plural && name === 'n') return '%d';
    if (!order.includes(name)) order.push(name);
    return `%${order.indexOf(name) + 1}$s`;
  });
  return { text: escaped, order };
}

function render(lang) {
  const dict = messages[lang];
  const lines = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by scripts/gen-android-strings.mjs from src/i18n.ts. Do not edit. -->', '<resources>'];
  const plurals = new Map();
  for (const [key, value] of Object.entries(dict)) {
    const m = /^plural\.(\w+)_(one|few|many|other)$/.exec(key);
    if (m) {
      if (!plurals.has(m[1])) plurals.set(m[1], {});
      plurals.get(m[1])[m[2]] = value;
      continue;
    }
    lines.push(`    <string name="${androidName(key)}">${toFormat(value, { plural: false }).text}</string>`);
  }
  for (const [name, forms] of plurals) {
    lines.push(`    <plurals name="${name}">`);
    for (const category of CATEGORIES[lang]) {
      lines.push(`        <item quantity="${category}">${toFormat(forms[category], { plural: true }).text}</item>`);
    }
    lines.push('    </plurals>');
  }
  lines.push('</resources>', '');
  return lines.join('\n');
}

const check = process.argv.includes('--check');
let outdated = false;
for (const [lang, file] of Object.entries(TARGETS)) {
  const path = resolve(resDir, file);
  const next = render(lang);
  if (check) {
    let current = '';
    try {
      current = readFileSync(path, 'utf8');
    } catch {
      // A missing file counts as outdated.
    }
    if (current !== next) {
      console.error(`${file} is out of date; run: node --experimental-strip-types scripts/gen-android-strings.mjs`);
      outdated = true;
    }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, next);
    console.log(`wrote ${file}`);
  }
}
process.exit(outdated ? 1 : 0);
